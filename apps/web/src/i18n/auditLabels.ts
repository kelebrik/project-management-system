/** Every audit label in both languages, for dictionary-wide checks. */
export const auditLabelCatalog = { actions, objects, fields } as const;

export function createAuditLabels(locale: Locale) {
  const pick = (labels: Record<string, LocalizedLabel>, key: string) => Object.hasOwn(labels, key) ? labels[key][locale] : key;
  return {
    auditActionLabel: (action: string) => pick(actions, action),
    auditObjectLabel: (event: AuditEventLike) => event.objectType === "Project" && !event.projectId ? event.objectType : pick(objects, event.objectType),
    auditFieldLabel: (field: string) => pick(fields, field),
  };
}
